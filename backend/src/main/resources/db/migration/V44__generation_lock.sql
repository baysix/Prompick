-- ============================================================================
-- 제작 잠금
--
-- 배포하면 서버가 내려갔다 올라온다. 그때 제작 중이던 작업은 끊기고, 10분 뒤 다른 워커가
-- 집어서 처음부터 다시 돌린다. 이미 AI 요금이 나간 호출을 한 번 더 하는 것이라 돈이 두 번 든다.
--
-- 그래서 배포 전에 새 제작을 받지 않는 스위치를 둔다. 잠그고 나면 이미 돌고 있는 작업만
-- 남고, 그것들은 늦어도 20분 안에 끝나거나 정리된다. 대기열이 빈 것을 확인하고 배포하면
-- 잃어버리는 작업도, 두 번 나가는 요금도 없다.
--
-- app_settings 에 두는 이유는 이 테이블이 처음부터 그 목적으로 만들어졌기 때문이다.
-- "배포 없이 정책을 바꾸기 위한 테이블" — 배포하려고 껐다 켜는 값이 배포를 해야 바뀐다면
-- 아무 쓸모가 없다.
-- ============================================================================

INSERT INTO app_settings (setting_key, value, description) VALUES
    ('generation.lock',
     '{"locked": false, "message": null, "lockedAt": null}',
     '제작 잠금. 배포 전에 켜서 대기열을 비운다')
ON CONFLICT (setting_key) DO NOTHING;
