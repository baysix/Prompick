-- ============================================================================
-- 예시 결과물의 실제 크기
--
-- 지금까지 목록의 타일 비율은 프론트가 순서대로 돌려가며 정했다. 올린 이미지가 정사각이든
-- 세로로 길든 상관없이 정해진 틀에 맞춰 잘렸다.
--
-- 운영자가 올린 그림이 잘려 나가는 것은 그냥 보기 나쁜 정도가 아니다. 예시 결과물은 사용자가
-- 템플릿을 고르는 유일한 근거인데, 그 그림의 구도를 우리가 마음대로 바꿔버리는 셈이다.
--
-- 그래서 올릴 때 크기를 재서 남긴다. 화면은 이 값으로 자리를 잡는다.
-- 크기를 읽을 수 없는 형식(SVG 등)은 비워두고, 화면이 템플릿 출력 비율로 대신한다.
-- ============================================================================

ALTER TABLE template_media
    ADD COLUMN width  INT,
    ADD COLUMN height INT;

COMMENT ON COLUMN template_media.width IS
    '원본 가로 픽셀. 목록에서 자리를 잡을 때 쓴다. 읽지 못한 형식은 NULL';
COMMENT ON COLUMN template_media.height IS '원본 세로 픽셀';
