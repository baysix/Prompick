-- ============================================================================
-- 직접 만들기 안내
--
-- 템플릿마다 "이것을 직접 만들려면 어떻게 하나"를 적어두는 자리다.
--
-- 왜 템플릿마다 따로 두는가. 영상은 만드는 길이 저마다 다르다. 어떤 것은 바탕 영상을
-- 구해 모션을 옮기는 것이고 어떤 것은 사진 한 장에서 움직임을 만드는 것이라, 한 곳에
-- 모아 적은 일반론으로는 아무것도 따라 할 수 없다.
--
-- upload_guide 와 섞지 않는다. 그쪽은 "우리가 만들어 줄 테니 사진을 이렇게 올려라"이고
-- 이쪽은 "직접 만들려면 저기 가서 이렇게 해라"다. 읽는 목적이 반대라 한 덩어리로 두면
-- 둘 다 읽히지 않는다.
--
-- 비워두면 화면에 아무것도 나오지 않는다. 안내를 적은 템플릿에만 탭이 생긴다.
--
-- 담기는 모양:
--   {
--     "toolName":   "Higgsfield Genjutsu",       -- 어떤 도구로 만드는지
--     "toolUrl":    "https://higgsfield.ai/...", -- 바로 가는 주소 (선택)
--     "intro":      "한두 줄 설명",
--     "steps":      ["1단계", "2단계", ...],
--     "tips":       ["요령", ...],               -- 선택
--     "costNote":   "요금 관련 한 줄"            -- 선택
--   }
--
-- 주의: 여기 적은 글은 로그인하지 않은 사람에게도 그대로 보인다. 파이프라인의 실제
-- 프롬프트를 옮겨 적으면 유료로 파는 프롬프트를 공짜로 내주는 셈이 된다. 무엇을 쓰는
-- 도구인지와 어떤 순서로 누르는지까지만 적는다.
-- ============================================================================

ALTER TABLE templates ADD COLUMN self_guide JSONB;

COMMENT ON COLUMN templates.self_guide IS
    '직접 만드는 법. 비어 있으면 화면에 탭이 생기지 않는다. 프롬프트 원문은 적지 않는다';
