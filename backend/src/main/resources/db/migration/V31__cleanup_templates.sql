-- ============================================================================
-- 템플릿 정리
--
-- 목록을 훑어보니 세 가지가 어긋나 있었다.
--
-- 1) 해상도가 실제 결과물과 다르다
--    파이프라인은 비율("9:16")로 적고 서버가 픽셀을 계산하는데, templates.resolution 에는
--    예전에 손으로 적은 값이 남아 있었다. 상세 화면에 "해상도 1080x1920"이라고 보여주면서
--    실제로는 864x1536을 내주고 있었다. 1:1 인데 1080x1920 으로 적힌 것도 있었다 —
--    그건 비율 표기 자체가 거짓말이 된다.
--
-- 2) 파이프라인 없이 공개된 템플릿이 있다
--    시드로 넣은 템플릿 중 둘은 활성 파이프라인이 아예 없다. 공개 버튼을 거쳤다면 막혔을
--    텐데, 시드는 INSERT 로 바로 넣어 그 검사를 지나쳤다. 사용자가 만들기를 누르면 실패한다.
--    나머지 둘은 MOCK 모델을 쓴다 — 돈은 안 들지만 목업 그림이 나온다.
--
-- 3) 만든 횟수가 지어낸 숫자다
--    시드 템플릿에 1243, 2104 같은 값이 박혀 있다. 상세 화면의 "만든 사람 N명"과 대시보드
--    누적 집계에 그대로 들어가 실제보다 부풀려 보인다. 실제 제작 기록은 0건이다.
-- ============================================================================

-- ---------------------------------------------------------------------------
-- 1. 해상도를 실제 결과물에 맞춘다
--
--    비율 변환기와 같은 규칙이다 — 긴 변 1536, 짧은 변은 비율에서 구해 16의 배수로 맞춤.
--    파이프라인에 비율이 적힌 템플릿만 손댄다.
-- ---------------------------------------------------------------------------
UPDATE templates t
   SET resolution = CASE p.steps->0->'params'->>'size'
           WHEN '9:16' THEN '864x1536'
           WHEN '2:3'  THEN '1024x1536'
           WHEN '3:4'  THEN '1152x1536'
           WHEN '4:5'  THEN '1232x1536'
           WHEN '1:1'  THEN '1536x1536'
           WHEN '3:2'  THEN '1536x1024'
           WHEN '16:9' THEN '1536x864'
           ELSE t.resolution
       END,
       ratio = coalesce(p.steps->0->'params'->>'size', t.ratio),
       updated_at = now()
  FROM template_pipelines p
 WHERE p.template_id = t.id
   AND p.active
   AND p.steps->0->'params'->>'size' ~ '^\d+:\d+$';

-- ---------------------------------------------------------------------------
-- 2. 실제로 만들 수 없는 템플릿을 내린다
--
--    지우지 않고 숨긴다. 시드에서 온 것이라 참고할 구석이 있고, 나중에 진짜 파이프라인을
--    붙여 되살릴 수도 있다. 숨김은 사용자에게 보이지 않는다는 점에서 내린 것과 같다.
-- ---------------------------------------------------------------------------
UPDATE templates
   SET status = 'HIDDEN',
       updated_at = now()
 WHERE slug IN (
    -- 활성 파이프라인이 없다. 만들기를 누르면 실패한다.
    'melting-dessert-closeup',
    'film-camera-portrait',
    -- MOCK 모델을 쓴다. 목업 그림이 나온다.
    'studio-product-shot',
    'cinematic-brand-film'
 );

-- ---------------------------------------------------------------------------
-- 3. 지어낸 제작 횟수를 지운다
--
--    실제 제작 기록에서 다시 센다. 없으면 0이 맞다. 부풀린 숫자는 사용자에게 보이는 곳이자
--    우리가 무엇이 인기인지 판단하는 근거라, 틀린 채로 두면 판단까지 틀어진다.
-- ---------------------------------------------------------------------------
UPDATE templates t
   SET generation_count = (
           SELECT count(*) FROM generation_jobs j
            WHERE j.template_id = t.id AND j.status = 'SUCCEEDED'
       ),
       updated_at = now();

-- ---------------------------------------------------------------------------
-- 4. 검증용으로 만든 템플릿을 지운다
--
--    @표시 두 개가 업로드 칸 두 개가 되는지 확인하려고 만든 것이다. 확인이 끝났고 제작
--    기록도 없다.
-- ---------------------------------------------------------------------------
DELETE FROM templates WHERE slug = 'two-photo-test';
