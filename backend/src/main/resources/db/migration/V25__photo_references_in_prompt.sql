-- ============================================================================
-- 사진 연결을 프롬프트 안으로 옮긴다.
--
-- 지금까지 연결은 프롬프트 밖에 따로 있었다(`image = person_photo`). 그래서 프롬프트를 고치다
-- 사진 이름이 바뀌어도 연결은 그대로 남았고, 어긋나도 아무도 몰랐다. 어긋나면 사진이 전달되지
-- 않은 채 글만으로 만들어지는데, 오류가 아니라 그냥 엉뚱한 그림이 나온다 — 가장 찾기 어려운
-- 종류의 고장이다.
--
-- 이제 프롬프트에 @이름으로 적고, 그 이름에 입력 칸을 잇는다. 무엇이 필요한지가 글을 읽는
-- 것만으로 드러나고, 빠뜨리면 관리자 화면이 "비어 있어요"로 알려준다.
--
-- 실행할 때는 @이름을 모델이 알아듣는 말("첨부한 사진", "첫 번째 사진")로 바꿔 보내고,
-- 사진도 글에서 부르는 차례대로 싣는다.
-- ============================================================================

-- ---------------------------------------------------------------------------
-- 미니미: 지시문 첫 줄의 "업로드된 실존 사진"을 표시로 바꾼다
-- ---------------------------------------------------------------------------
UPDATE template_pipelines p
   SET steps = jsonb_set(
           jsonb_set(
               p.steps,
               '{0,prompt}',
               to_jsonb(replace(
                   p.steps->0->>'prompt',
                   '업로드된 실존 사진을 기반으로 작업.',
                   '@아이사진 을 기반으로 작업.'))
           ),
           '{0,inputs}',
           jsonb_build_object('@아이사진', 'child_photo')
       ),
       updated_at = now()
 WHERE p.template_id = (SELECT id FROM templates WHERE slug = 'minime-playground');

-- ---------------------------------------------------------------------------
-- 잠금화면: "업로드한 사진의 인물"을 표시로 바꾼다
-- ---------------------------------------------------------------------------
UPDATE template_pipelines p
   SET steps = jsonb_set(
           jsonb_set(
               p.steps,
               '{0,prompt}',
               to_jsonb(replace(
                   p.steps->0->>'prompt',
                   '업로드한 사진의 인물은 그대로 유지한 채,',
                   '@인물사진 의 인물은 그대로 유지한 채,'))
           ),
           '{0,inputs}',
           jsonb_build_object('@인물사진', 'person_photo')
       ),
       updated_at = now()
 WHERE p.template_id = (SELECT id FROM templates WHERE slug = 'lockscreen-peekaboo');
