-- ============================================================================
-- 앞에 세울 추론 모델을 gpt-5.4로 고정한다.
--
-- 처음엔 gpt-6-astra를 썼는데, 실제로 토큰을 재보니 이 단계는 입력 3,318 / 출력 490 토큰밖에
-- 쓰지 않았다. 사진을 보고 지시문을 읽어 이미지 툴을 부르는 것이 전부라 깊은 추론이 없다는 뜻이다.
-- astra의 비싼 값은 대부분 출력 단가($50/1M)에 있는데, 쓰지도 않는 능력에 돈을 낸 셈이었다.
--
-- gpt-5.4로 바꾸면 추론 단계가 81원에서 22원으로 줄어든다. 더 싼 mini(7원)도 결과가 나쁘지
-- 않았지만, 기본값은 여유를 두고 gpt-5.4로 잡는다 — 지시문이 길어지거나 템플릿이 복잡해졌을 때
-- 흔들리지 않는 쪽이 기본값에 맞다.
-- ============================================================================

UPDATE template_pipelines p
   SET steps = jsonb_set(p.steps, '{0,params,mainlineModel}', '"gpt-5.4"'),
       updated_at = now()
 WHERE p.template_id = (SELECT id FROM templates WHERE slug = 'minime-playground');

-- ---------------------------------------------------------------------------
-- 실측 원가를 반영한다.
--
-- 이 단계 한 번에는 추론 모델 요금과 이미지 생성 요금이 함께 든다. 원가 계산은 단계별 모델의
-- unit_cost_krw 를 더하는 구조이므로, 이 행에 두 값의 합을 담는다. 그렇게 하지 않으면
-- 추론 요금이 어디에도 잡히지 않아 매출·원가 화면이 실제보다 남는 것처럼 보인다.
-- ---------------------------------------------------------------------------
UPDATE ai_models
   SET unit_cost_krw = 302,
       memo = 'Responses API image_generation 툴. 원가 302원 = 추론(gpt-5.4, 실측 3318/490토큰 기준 22원) + 이미지 280원. 환율·단가가 바뀌면 다시 잰다'
 WHERE provider = 'OPENAI' AND model_key = 'gpt-image-2.5-sunburst';
