-- ============================================================================
-- 해상도 선택지 모양을 바로잡는다
--
-- V40 에서 '["480p","720p"]' 으로 넣었는데, 이 칸은 [{"value":…,"label":…}] 모양이다.
-- 엔티티가 List<Map<String,Object>> 로 읽으므로 문자열 배열은 꺼내는 순간 깨진다.
--
-- 그리고 그 깨짐이 이 템플릿 하나에서 끝나지 않았다. 템플릿을 읽다가 예외가 나면서 상세
-- 응답 전체가 500 이 됐다. 선택지 하나가 다른 모든 것을 가린 셈이다.
--
-- 겸사겸사 label 에 값이 두 배 차이라는 것을 적는다. 화질을 고르는 자리에서 그 사실을
-- 모르면 대부분 비싼 쪽을 고른다.
-- ============================================================================

UPDATE template_input_fields
   SET options = '[{"value":"480p","label":"480p — 기본"},
                   {"value":"720p","label":"720p — 더 선명, 값은 두 배"}]'::jsonb
 WHERE field_key = '해상도'
   AND template_id = (SELECT id FROM templates WHERE slug = 'genjutsu-school-crowd');
